#!/usr/bin/env node
/**
 * Builds `dist/` from `src/` and the pika relay modules it shares with the Pi extension, with
 * TypeScript's `transpileModule` (no bundler, no type check: `npm run typecheck` does that).
 * Codex copies the plugin directory when it installs it, so `dist/` is committed and must stand
 * alone: shared files land in `dist/shared/`, and every `.ts` import becomes `.js`.
 *
 *     node plugins/pika-relay/scripts/build.mjs [--out <dir>]
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(root, "../..");
const outIndex = process.argv.indexOf("--out");
const out = outIndex >= 0 ? resolve(process.argv[outIndex + 1]) : join(root, "dist");

/** Shared files from the Pi extension, by their path under `extensions/pika/`. */
const SHARED = ["config.ts", "repository.ts", "relay/protocol.ts", "relay/connection.ts"];
const SHARED_PREFIX = "../../../extensions/pika/";

const options = { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2023, removeComments: false, newLine: ts.NewLineKind.LineFeed };

/** Rewrites relative `.ts` specifiers to `.js`, and `src/`'s imports of shared files to `./shared/`. */
function rewrite(code, fromSrc) {
    return code.replace(/(\bfrom\s+|\bimport\s*\(\s*|\bimport\s+)(["'])(\.{1,2}\/[^"']+)\2/g, (_match, lead, quote, specifier) => {
        let target = specifier;
        if (fromSrc && target.startsWith(SHARED_PREFIX)) target = `./shared/${target.slice(SHARED_PREFIX.length)}`;
        return `${lead}${quote}${target.replace(/\.ts$/, ".js")}${quote}`;
    });
}

function emit(source, target, fromSrc) {
    const input = readFileSync(source, "utf8");
    const { outputText } = ts.transpileModule(input, { compilerOptions: options, fileName: source });
    const header = `// Generated by plugins/pika-relay/scripts/build.mjs from ${relative(repo, source)}; do not edit.\n`;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, header + rewrite(outputText, fromSrc));
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const name of readdirSync(join(root, "src")).filter((file) => file.endsWith(".ts")).sort()) {
    emit(join(root, "src", name), join(out, name.replace(/\.ts$/, ".js")), true);
}
for (const path of SHARED) emit(join(repo, "extensions/pika", path), join(out, "shared", path.replace(/\.ts$/, ".js")), false);
// The installed plugin has no package.json above it to make `.js` ESM.
writeFileSync(join(out, "package.json"), `${JSON.stringify({ type: "module", private: true }, null, 2)}\n`);
